import type { Metadata } from "next";
import { notFound } from "next/navigation";

import {
  SOCIAL_CARD_CONTENT_TYPE,
  SOCIAL_CARD_ID,
  SOCIAL_CARD_SIZE,
} from "@/components/metadata/social-card-config";
import { getDictionary } from "@/content/dictionaries";
import type {
  MessageDictionary,
  PageMetadata as PageMetadataMessages,
} from "@/content/messages";
import {
  getSiteUrlConfiguration,
  SITE_NAME,
  type SiteUrlConfiguration,
} from "@/content/site";
import { isLocale, type Locale } from "@/i18n/config";
import {
  getHreflangMap,
  getLocalizedHrefMap,
  localizePath,
  type LocalizedHrefMap,
  type PagePath,
} from "@/i18n/paths";

const OPEN_GRAPH_LOCALES = {
  de: "de_AT",
  en: "en_GB",
} as const satisfies Record<Locale, string>;

export type MetadataPageKey =
  "home" | "product" | "contact" | "privacy" | "imprint";

export type ArticleMetadataOptions = Readonly<{
  /** ISO date (YYYY-MM-DD) of first publication. */
  publishedTime: string;
  /** ISO date (YYYY-MM-DD) of the last material change. */
  modifiedTime: string;
  authors: readonly string[];
}>;

type CreatePageMetadataBaseOptions = Readonly<{
  locale: Locale;
  messages: PageMetadataMessages;
  siteConfiguration?: SiteUrlConfiguration;
  /** Marks the page as an Open Graph article (guides). */
  article?: ArticleMetadataOptions;
}>;

export type CreatePageMetadataOptions = CreatePageMetadataBaseOptions &
  (
    | Readonly<{
        /** A page that exists in every supported locale. */
        pagePath: PagePath;
        localizedPaths?: never;
      }>
    | Readonly<{
        pagePath?: never;
        /**
         * Public paths of a page keyed by the locales it exists in. Must
         * contain `locale`. Single-locale pages get a canonical URL and no
         * hreflang alternates.
         */
        localizedPaths: LocalizedHrefMap;
      }>
  );

export function getAbsoluteUrl(baseUrl: URL, path: string): string {
  return new URL(path, baseUrl).toString();
}

/**
 * Social image routes generated by app/[locale]/opengraph-image.tsx and
 * twitter-image.tsx, addressed by their public URLs: English unprefixed
 * (served through the root rewrite in src/i18n/routing.ts), German under
 * `/de`. Like every other `/en/*` URL, the prefixed English image URLs 308 to
 * these paths.
 */
export function getSocialImagePaths(locale: Locale) {
  return {
    openGraph: localizePath(locale, `/opengraph-image/${SOCIAL_CARD_ID}`),
    twitter: localizePath(locale, `/twitter-image/${SOCIAL_CARD_ID}`),
  } as const;
}

export function createPageMetadata(
  options: CreatePageMetadataOptions,
): Metadata {
  const {
    locale,
    messages,
    siteConfiguration = getSiteUrlConfiguration(),
  } = options;
  const localizedPaths: LocalizedHrefMap =
    options.pagePath !== undefined
      ? getLocalizedHrefMap(options.pagePath)
      : options.localizedPaths;
  const ownPath = localizedPaths[locale];

  if (ownPath === undefined) {
    throw new Error(
      `createPageMetadata: the page has no ${locale} path; localizedPaths must include the rendered locale.`,
    );
  }

  const canonicalBaseUrl = siteConfiguration.canonicalBaseUrl;
  const canonicalUrl = canonicalBaseUrl
    ? getAbsoluteUrl(canonicalBaseUrl, ownPath)
    : undefined;
  const hreflang = getHreflangMap(localizedPaths);
  // A single-locale page has no counterpart and no x-default; it only
  // declares its own language (self-referencing hreflang).
  const languagePaths =
    Object.keys(hreflang).length > 0 ? hreflang : { [locale]: ownPath };
  const languageAlternates = canonicalBaseUrl
    ? Object.fromEntries(
        Object.entries(languagePaths).map(([language, path]) => [
          language,
          getAbsoluteUrl(canonicalBaseUrl, path),
        ]),
      )
    : undefined;
  const alternateOpenGraphLocales = (["de", "en"] as const)
    .filter((other) => other !== locale && localizedPaths[other] !== undefined)
    .map((other) => OPEN_GRAPH_LOCALES[other]);
  const socialImages = getSocialImagePaths(locale);

  return {
    metadataBase: siteConfiguration.metadataBaseUrl,
    applicationName: SITE_NAME,
    title: messages.title,
    description: messages.description,
    alternates: canonicalUrl
      ? {
          canonical: canonicalUrl,
          ...(languageAlternates ? { languages: languageAlternates } : {}),
        }
      : undefined,
    robots: siteConfiguration.isIndexable
      ? {
          index: true,
          follow: true,
        }
      : {
          index: false,
          follow: false,
          nocache: true,
          googleBot: {
            index: false,
            follow: false,
            noimageindex: true,
          },
        },
    openGraph: {
      title: messages.title,
      description: messages.description,
      ...(canonicalUrl ? { url: canonicalUrl } : {}),
      siteName: SITE_NAME,
      locale: OPEN_GRAPH_LOCALES[locale],
      ...(alternateOpenGraphLocales.length > 0
        ? { alternateLocale: alternateOpenGraphLocales }
        : {}),
      ...(options.article
        ? {
            type: "article" as const,
            publishedTime: options.article.publishedTime,
            modifiedTime: options.article.modifiedTime,
            authors: [...options.article.authors],
          }
        : { type: "website" as const }),
      images: [
        {
          url: socialImages.openGraph,
          width: SOCIAL_CARD_SIZE.width,
          height: SOCIAL_CARD_SIZE.height,
          type: SOCIAL_CARD_CONTENT_TYPE,
          alt: messages.title,
        },
      ],
    },
    twitter: {
      card: "summary_large_image",
      title: messages.title,
      description: messages.description,
      images: [
        {
          url: socialImages.twitter,
          width: SOCIAL_CARD_SIZE.width,
          height: SOCIAL_CARD_SIZE.height,
          type: SOCIAL_CARD_CONTENT_TYPE,
          alt: messages.title,
        },
      ],
    },
  };
}

type GenerateLocalizedPageMetadataOptions = Readonly<{
  params: Promise<{ locale: string }>;
  pagePath: PagePath;
  pageKey: MetadataPageKey;
}>;

export async function generateLocalizedPageMetadata({
  params,
  pagePath,
  pageKey,
}: GenerateLocalizedPageMetadataOptions): Promise<Metadata> {
  const { locale } = await params;

  if (!isLocale(locale)) {
    notFound();
  }

  const dictionary: MessageDictionary = getDictionary(locale);

  return createPageMetadata({
    locale,
    pagePath,
    messages: dictionary[pageKey].metadata,
  });
}
