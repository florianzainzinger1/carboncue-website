// Only the registered German guides exist; every other slug and every
// non-German locale is a 404 (dynamicParams = false).
export const dynamicParams = false;

/**
 * Next.js calls this once per locale generated by the [locale] layout and
 * merges each result over that parent's params. Returning an empty array for
 * English would pass `{ locale: "en" }` through without a slug, which makes
 * the param set incomplete and silently prerenders nothing (Next 16.3,
 * build/static-paths/app.js). So every call returns the complete German
 * params, overriding the parent locale; duplicates are removed by Next, and
 * no English guide path is ever generated.
 */
export function generateStaticParams(): { locale: string; slug: string }[] {
  return GUIDES.map((guide) => ({ locale: guide.locale, slug: guide.slug }));
}
async function resolveGuide(
  params: PageProps<"/[locale]/eu-ets/[slug]">["params"],
): Promise<GuideEntry> {
  const { locale, slug } = await params;
  const guide = locale === GUIDE_LOCALE ? getGuideBySlug(slug) : undefined;

  if (!guide) {
    notFound();
  }

  return guide;
}

export async function generateMetadata({
  params,
}: PageProps<"/[locale]/eu-ets/[slug]">) {
  const guide = await resolveGuide(params);

  return createPageMetadata({
    locale: guide.locale,
    localizedPaths: { [guide.locale]: getGuidePath(guide.slug) },
    messages: {
      title: getGuideDocumentTitle(guide.content.metaTitle),
      description: guide.content.metaDescription,
    },
    article: {
      publishedTime: guide.publishedOn,
      modifiedTime: guide.updatedOn,
      authors: FOUNDER_PROFILES.map((founder) => founder.name),
    },
  });
}

type GuideArticleProps = Readonly<{ guide: GuideEntry }>;

export function GuideArticle({ guide }: GuideArticleProps) {
  const { content } = guide;
  const otherGuides = GUIDES.filter((other) => other.slug !== guide.slug);
  const breadcrumbItems = getGuideBreadcrumbSteps(guide).map((step) => ({
    name: step.name,
    href: step.path,
  }));

  return (
    <article aria-labelledby="guide-title">
      <div className="border-border bg-canvas px-page py-section border-b">
        <div className="max-w-site mx-auto">
          <div className="max-w-3xl">
            <GuideBreadcrumb items={breadcrumbItems} />
            <p className="text-primary mb-5 font-mono text-xs font-medium tracking-[0.14em] uppercase">
              {content.eyebrow}
            </p>
            <Heading id="guide-title" as="h1" size="title">
              {content.h1}
            </Heading>
            <Prose className="mt-7" size="lead">
              <CitedText text={content.lead} />
            </Prose>
            <p className="text-muted mt-6 text-sm leading-6">
              <span data-guide-updated>
                {guidePageLabels.updatedOnPrefix}{" "}
                <time dateTime={guide.updatedOn}>
                  {formatGermanLongDate(guide.updatedOn)}
                </time>
              </span>
              <span aria-hidden="true"> · </span>
              <span>
                {guidePageLabels.responsiblePrefix} {GUIDE_RESPONSIBLE_NAMES}
              </span>
            </p>
          </div>
        </div>
      </div>

      <div className="bg-surface px-page py-section">
        <div className="max-w-reading mx-auto grid min-w-0 gap-12">
          <section
            aria-labelledby="guide-key-facts-title"
            className="rounded-card border-border bg-surface-muted p-panel border"
          >
            <Heading id="guide-key-facts-title" as="h2" size="subsection">
              {guidePageLabels.keyFactsTitle}
            </Heading>
            <ul className="text-ink-soft mt-4 grid list-disc gap-3 pl-5 text-base leading-7">
              {content.keyFacts.map((fact) => (
                <li key={fact}>
                  <CitedText text={fact} />
                </li>
              ))}
            </ul>
          </section>

          {content.sections.map((section) => (
            <section
              key={section.id}
              id={section.id}
              aria-labelledby={`${section.id}-title`}
              className="grid min-w-0 gap-5"
            >
              <Heading id={`${section.id}-title`} as="h2" size="section">
                {section.heading}
              </Heading>
              {section.paragraphs.map((paragraph) => (
                <Prose key={paragraph}>
                  <CitedText text={paragraph} />
                </Prose>
              ))}
              {section.bullets && (
                <ul className="text-ink-soft max-w-reading grid list-disc gap-3 pl-5 text-base leading-7 md:text-lg md:leading-8">
                  {section.bullets.map((bullet) => (
                    <li key={bullet}>
                      <CitedText text={bullet} />
                    </li>
                  ))}
                </ul>
              )}
              {section.table && <GuideTable table={section.table} />}
            </section>
          ))}

          <section aria-labelledby="guide-faq-title" className="grid gap-6">
            <Heading id="guide-faq-title" as="h2" size="section">
              {guidePageLabels.faqTitle}
            </Heading>
            {content.faq.map((item) => (
              <div key={item.question}>
                <Heading as="h3" size="subsection">
                  {item.question}
                </Heading>
                <Prose className="mt-2">
                  <CitedText text={item.answer} />
                </Prose>
              </div>
            ))}
          </section>

          <section aria-labelledby="guide-sources-title">
            <Heading id="guide-sources-title" as="h2" size="section">
              {guidePageLabels.sourcesTitle}
            </Heading>
            <ol className="text-ink-soft mt-5 grid list-decimal gap-4 pl-6 text-sm leading-6 [overflow-wrap:anywhere]">
              {content.sources.map((source) => (
                <li
                  key={source.id}
                  id={getSourceAnchorId(source.id)}
                  value={source.id}
                  className="scroll-mt-40"
                >
                  <a
                    href={source.url}
                    rel="noopener"
                    className="text-ink rounded-control font-medium underline underline-offset-4 hover:no-underline"
                  >
                    {source.label}
                  </a>
                  <span className="block">{source.publisher}</span>
                  <span className="text-muted block">
                    {guidePageLabels.retrievedOnPrefix}{" "}
                    <time dateTime={source.retrievedOn}>
                      {formatGermanNumericDate(source.retrievedOn)}
                    </time>
                  </span>
                </li>
              ))}
            </ol>
          </section>

          <Callout title={guidePageLabels.disclaimerTitle}>
            <p>{content.disclaimer}</p>
          </Callout>

          <nav
            aria-labelledby="guide-more-title"
            className="border-border border-t pt-10"
          >
            <Heading id="guide-more-title" as="h2" size="section">
              {guidePageLabels.moreGuidesTitle}
            </Heading>
            <ul className="mt-5 grid gap-3 text-base leading-7">
              {otherGuides.map((other) => (
                <li key={other.slug}>
                  <Link
                    href={getGuidePath(other.slug)}
                    className="text-ink rounded-control font-medium underline underline-offset-4 hover:no-underline"
                  >
                    {other.content.h1}
                  </Link>
                </li>
              ))}
              <li>
                <Link
                  href={getGuideHubPath()}
                  className="text-ink rounded-control font-medium underline underline-offset-4 hover:no-underline"
                >
                  {guidePageLabels.hubLinkLabel}
                </Link>
              </li>
            </ul>
          </nav>
        </div>
      </div>
    </article>
  );
}

export default async function GuidePage({
  params,
}: PageProps<"/[locale]/eu-ets/[slug]">) {
  const guide = await resolveGuide(params);
  const dictionary = getDictionary(guide.locale);

  return (
    <SiteShell
      dictionary={dictionary}
      locale={guide.locale}
      alternateHrefs={{ [guide.locale]: getGuidePath(guide.slug) }}
      activeNavigationPath={null}
    >
      <StructuredDataScript data={createGuideArticleStructuredData(guide)} />
      <StructuredDataScript
        data={createBreadcrumbStructuredData(getGuideBreadcrumbSteps(guide))}
      />
      <GuideArticle guide={guide} />
    </SiteShell>
  );
}
